public class UnicodeIdentifiers {
    static final String café = "espresso";
    static final String naïve = "sans accent";

    static int Σsum(int... 数値) {
        int 合計 = 0;
        for (int 値 : 数値) {
            合計 += 値;
        }
        return 合計;
    }

    static double λ(double x) {
        double π = Math.PI;
        return x * π;
    }
}
